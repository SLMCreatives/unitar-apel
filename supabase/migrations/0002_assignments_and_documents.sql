  end,
  nullif(l.moderator_appointment_date::text, '')::date,
  case when l.moderator_appointment_date is not null then 'ISSUED' else 'PENDING' end
from apel l
where l.moderator is not null
  and not exists (
    select 1 from apel_assignments x
    where x.learner_id = l.id and x.role = 'MODERATOR'
  );

-- ---------------------------------------------------------------------------
-- Private storage bucket for uploaded documents. Files are never served from
-- public paths — the app generates short-lived signed URLs for downloads.
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public)
values ('apel-documents', 'apel-documents', false)
on conflict (id) do nothing;

-- v1 runs without login, so the anon key gets full access (same caveat as
-- 0001). Before exposing this app outside the unit, add Supabase Auth and
-- tighten these policies.
alter table apel_assignments enable row level security;
alter table apel_documents enable row level security;

drop policy if exists "tracker anon full access" on apel_assignments;
create policy "tracker anon full access" on apel_assignments
  for all using (true) with check (true);
drop policy if exists "tracker anon full access" on apel_documents;
create policy "tracker anon full access" on apel_documents
  for all using (true) with check (true);

drop policy if exists "apel documents bucket access" on storage.objects;
create policy "apel documents bucket access" on storage.objects
  for all
  using (bucket_id = 'apel-documents')
  with check (bucket_id = 'apel-documents');
