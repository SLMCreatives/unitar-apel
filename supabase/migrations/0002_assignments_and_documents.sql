-- UNITAR APEL.Q Tracker — per-assignment tracking and document uploads.
-- Run this in the Supabase SQL Editor after 0001_assessors_and_notes.sql.
--
-- Adds:
--   apel_assignments — one row per learner + personnel role + assessment stage,
--     so claims and appointment letters are tracked separately for each stage.
--   apel_documents   — metadata for files stored in the private
--     'apel-documents' storage bucket.

create table if not exists apel_assignments (
  id bigint generated by default as identity primary key,
  learner_id bigint not null references apel (id) on delete cascade,
  personnel_name text not null,
  role text not null check (
    role in ('ADVISOR', 'INTERNAL_ASSESSOR', 'EXTERNAL_ASSESSOR', 'MODERATOR')
  ),
  stage text,
  payment_mode text,
  claim_status text,
  appointment_date date,
  appointment_letter_status text not null default 'PENDING',
  remarks text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Moderators are not paid through this process, so claim fields must stay empty.
  constraint apel_assignments_moderator_no_claim check (
    role <> 'MODERATOR' or (claim_status is null and payment_mode is null)
  )
);

-- One assignment per learner + role + stage (null stages collapse to '').
create unique index if not exists apel_assignments_learner_role_stage_key
  on apel_assignments (learner_id, role, coalesce(stage, ''));
create index if not exists apel_assignments_learner_id_idx
  on apel_assignments (learner_id);
create index if not exists apel_assignments_role_name_idx
  on apel_assignments (role, personnel_name);

create or replace function apel_touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists apel_assignments_touch on apel_assignments;
create trigger apel_assignments_touch
  before update on apel_assignments
  for each row execute function apel_touch_updated_at();

create table if not exists apel_documents (
  id bigint generated by default as identity primary key,
  learner_id bigint not null references apel (id) on delete cascade,
  -- Null for learner-level documents; set for personnel-assignment documents.
  assignment_id bigint references apel_assignments (id) on delete cascade,
  personnel_role text check (
    personnel_role in ('ADVISOR', 'INTERNAL_ASSESSOR', 'EXTERNAL_ASSESSOR', 'MODERATOR')
  ),
  document_category text,
  original_file_name text not null,
  storage_path text not null,
  mime_type text,
  file_size bigint,
  uploaded_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists apel_documents_learner_id_idx
  on apel_documents (learner_id);
create index if not exists apel_documents_assignment_id_idx
  on apel_documents (assignment_id);

drop trigger if exists apel_documents_touch on apel_documents;
create trigger apel_documents_touch
  before update on apel_documents
  for each row execute function apel_touch_updated_at();

-- ---------------------------------------------------------------------------
-- Backfill: create one assignment per personnel column already filled in on
-- apel, so no existing advisor/assessor/moderator information is lost. The
-- stage is copied from the learner's current assessment stage when it maps to
-- an assessable stage. Appointment-letter status is assumed ISSUED when an
-- appointment date was already recorded — adjust individual records if wrong.
-- ---------------------------------------------------------------------------

insert into apel_assignments
  (learner_id, personnel_name, role, stage, appointment_date, appointment_letter_status, payment_mode)
select
  l.id,
  l.advisor,
  'ADVISOR',
  case
    when l.assessment_stage in ('SELF ASSESSMENT', 'PORTFOLIO', 'FVV', 'CHALLENGE TEST', 'CAPSTONE')
    then l.assessment_stage
  end,
  nullif(l.advisor_appointment_date::text, '')::date,
  case when l.advisor_appointment_date is not null then 'ISSUED' else 'PENDING' end,
  (select a.advisor_payment_mode from apel_advisors a where a.advisor_name = l.advisor limit 1)
from apel l
where l.advisor is not null
  and not exists (
    select 1 from apel_assignments x
    where x.learner_id = l.id and x.role = 'ADVISOR'
  );

insert into apel_assignments
  (learner_id, personnel_name, role, stage, appointment_date, appointment_letter_status)
select
  l.id,
  l.internal_assessor,
  'INTERNAL_ASSESSOR',
  case
    when l.assessment_stage in ('SELF ASSESSMENT', 'PORTFOLIO', 'FVV', 'CHALLENGE TEST', 'CAPSTONE')
    then l.assessment_stage
  end,
  nullif(l.internal_assessor_appointment_date::text, '')::date,
  case when l.internal_assessor_appointment_date is not null then 'ISSUED' else 'PENDING' end
from apel l
where l.internal_assessor is not null
  and not exists (
    select 1 from apel_assignments x
    where x.learner_id = l.id and x.role = 'INTERNAL_ASSESSOR'
  );

insert into apel_assignments
  (learner_id, personnel_name, role, stage, appointment_date, appointment_letter_status)
select
  l.id,
  l.external_assessor,
  'EXTERNAL_ASSESSOR',
  case
    when l.assessment_stage in ('SELF ASSESSMENT', 'PORTFOLIO', 'FVV', 'CHALLENGE TEST', 'CAPSTONE')
    then l.assessment_stage
  end,
  nullif(l.external_assessor_appointment_date::text, '')::date,
  case when l.external_assessor_appointment_date is not null then 'ISSUED' else 'PENDING' end
from apel l
where l.external_assessor is not null
  and not exists (
    select 1 from apel_assignments x
    where x.learner_id = l.id and x.role = 'EXTERNAL_ASSESSOR'
  );

insert into apel_assignments
  (learner_id, personnel_name, role, stage, appointment_date, appointment_letter_status)
select
  l.id,
  l.moderator,
  'MODERATOR',
  case
    when l.assessment_stage in ('SELF ASSESSMENT', 'PORTFOLIO', 'FVV', 'CHALLENGE TEST', 'CAPSTONE')
