-- UNITAR APEL.Q Tracker — authentication, access roles and locked-down RLS.
-- Run this in the Supabase SQL Editor AFTER 0001 and 0002.
--
-- DO NOT RUN THIS YET. Auth is switched off in the app while it is still being
-- built (see AUTH_ENABLED in src/lib/auth-config.ts). Applying this migration
-- replaces the anon-access policies with ones that require a signed-in user,
-- so the app would immediately stop reading and writing data. Run it at the
-- same time as flipping AUTH_ENABLED back to true.
--
-- This migration turns the app from "anon key, wide-open" into an
-- authenticated app:
--   app_roles  — editable access roles (a role = a set of allowed sections).
--   profiles   — one row per auth.users account, holding status + role +
--                superadmin flag. Created automatically on signup by a trigger.
-- It then REPLACES every "tracker anon full access" policy from 0001/0002 with
-- policies that require an active, authenticated user, and restricts the
-- privilege tables (profiles, app_roles) to superadmins only — so a normal
-- user can never escalate their own access.

-- ---------------------------------------------------------------------------
-- Access roles. `sections` is the list of app sections the role may use; the
-- allowed keys mirror src/lib/permissions.ts (dashboard, learners, advisors,
-- assessors, reports).
-- ---------------------------------------------------------------------------
create table if not exists app_roles (
  id bigint generated by default as identity primary key,
  key text not null unique,
  label text not null,
  sections text[] not null default '{}',
  is_system boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Starter roles — superadmins can edit these or add their own later.
insert into app_roles (key, label, sections, is_system)
values
  ('coordinator', 'Coordinator',
   array['dashboard', 'learners', 'advisors', 'assessors', 'reports'], true),
  ('viewer', 'Viewer', array['dashboard', 'reports'], true)
on conflict (key) do nothing;

-- ---------------------------------------------------------------------------
-- Profiles. One per auth user. role_id is null until a superadmin assigns one.
-- status starts at 'pending' — a pending or disabled account has no access.
-- ---------------------------------------------------------------------------
create table if not exists profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  full_name text,
  role_id bigint references app_roles (id) on delete set null,
  status text not null default 'pending'
    check (status in ('pending', 'active', 'disabled')),
  is_superadmin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists profiles_role_id_idx on profiles (role_id);

-- Reuse (or (re)create) the shared updated_at trigger function from 0002.
create or replace function apel_touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists app_roles_touch on app_roles;
create trigger app_roles_touch
  before update on app_roles
  for each row execute function apel_touch_updated_at();

drop trigger if exists profiles_touch on profiles;
create trigger profiles_touch
  before update on profiles
  for each row execute function apel_touch_updated_at();

-- ---------------------------------------------------------------------------
-- New-user hook: create a profile whenever an auth user is created.
-- The seeded email is granted superadmin + active immediately so there is a
-- first administrator who can approve everyone else. To change or add seed
-- admins, edit the email(s) in the `when` clause below.
-- SECURITY DEFINER so it can insert into profiles regardless of RLS.
-- ---------------------------------------------------------------------------
create or replace function handle_new_user() returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  seed_admin boolean := new.email = 'sulaiman.munaff@unitar.my';
begin
  insert into profiles (id, email, full_name, status, is_superadmin)
  values (
    new.id,
    new.email,
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    case when seed_admin then 'active' else 'pending' end,
    seed_admin
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

-- ---------------------------------------------------------------------------
-- Authorization helpers. SECURITY DEFINER so policies that call them read
-- profiles with the definer's rights — this avoids infinite recursion in the
-- profiles RLS policies (a policy on profiles that itself queries profiles).
-- ---------------------------------------------------------------------------
create or replace function public.is_active_user() returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from profiles
    where id = auth.uid() and status = 'active'
  );
$$;

create or replace function public.is_superadmin() returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from profiles
    where id = auth.uid() and is_superadmin
  );
$$;

-- ---------------------------------------------------------------------------
-- RLS: privilege tables.
-- ---------------------------------------------------------------------------
alter table profiles enable row level security;
alter table app_roles enable row level security;

-- Profiles: a user may read only their own row; superadmins read all. Only
-- superadmins may insert/update/delete — so normal users cannot change their
-- own role, status or superadmin flag. (The signup trigger above inserts rows
-- as SECURITY DEFINER, so it is unaffected by this write restriction.)
drop policy if exists "profiles self or admin read" on profiles;
create policy "profiles self or admin read" on profiles
  for select to authenticated
  using (id = auth.uid() or public.is_superadmin());

drop policy if exists "profiles admin write" on profiles;
create policy "profiles admin write" on profiles
  for all to authenticated
  using (public.is_superadmin())
  with check (public.is_superadmin());

-- Access roles: any authenticated user may read (the app needs the section
-- list to render); only superadmins may change them.
drop policy if exists "app_roles read" on app_roles;
create policy "app_roles read" on app_roles
  for select to authenticated
  using (true);

drop policy if exists "app_roles admin write" on app_roles;
create policy "app_roles admin write" on app_roles
  for all to authenticated
  using (public.is_superadmin())
  with check (public.is_superadmin());

-- ---------------------------------------------------------------------------
-- RLS: data tables. Drop the wide-open anon policies from 0001/0002 and
-- require an active, authenticated user instead. Section-level permission
-- (which role may use which section) is enforced in the app layer
-- (src/lib/auth.ts guards); RLS here is the hard "must be a signed-in, active
-- user" boundary that the public anon key can no longer satisfy.
-- ---------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'apel', 'apel_advisors', 'apel_assessors', 'apel_notes',
    'apel_assignments', 'apel_documents'
  ]
  loop
    execute format('alter table %I enable row level security;', t);
    execute format('drop policy if exists "tracker anon full access" on %I;', t);
    execute format(
      'create policy "active users full access" on %I
         for all to authenticated
         using (public.is_active_user())
         with check (public.is_active_user());', t);
  end loop;
end;
$$;

-- ---------------------------------------------------------------------------
-- Storage: the private apel-documents bucket is now for authenticated users
-- only (downloads still go through short-lived signed URLs generated server
-- side). Replaces the open policy from 0002.
-- ---------------------------------------------------------------------------
drop policy if exists "apel documents bucket access" on storage.objects;
drop policy if exists "apel documents authenticated access" on storage.objects;
create policy "apel documents authenticated access" on storage.objects
  for all to authenticated
  using (bucket_id = 'apel-documents')
  with check (bucket_id = 'apel-documents');
