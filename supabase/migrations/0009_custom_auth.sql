-- UNITAR APEL.Q Tracker — email one-time-code login, without Supabase Auth.
-- Run this in the Supabase SQL Editor after 0008_note_follow_up_done.sql.
--
-- Why not Supabase Auth
-- ---------------------
-- This Supabase project is shared with another UNITAR app, whose access rule is
-- "any confirmed @unitar.my user in auth.users". Signing APEL users up in
-- auth.users would therefore also hand them that app's data. APEL keeps its own
-- accounts instead:
--
--   apel_users        one row per person who may sign in (email + role +
--                     status), replacing public.profiles from 0003, which is
--                     tied to auth.users.
--   apel_login_codes  short-lived 6-digit codes emailed at sign-in (only a
--                     sha256 hash is stored).
--   apel_sessions     server-side sessions; the browser holds a random token in
--                     an httpOnly cookie, and only its sha256 hash is stored.
--
-- All three are reachable ONLY with the server-side secret key (service_role):
-- RLS is on with no policies, and anon / authenticated have no grants. The app
-- reads and writes them from Server Components / Server Actions only.
--
-- This migration is additive — it does not change any existing table's access.
-- Locking the existing APEL tables down is 0010, applied after the app is
-- deployed with SUPABASE_SECRET_KEY.

-- ---------------------------------------------------------------------------
-- Accounts
-- ---------------------------------------------------------------------------
create table if not exists apel_users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique check (email = lower(email)),
  full_name text,
  role_id bigint references app_roles (id) on delete set null,
  status text not null default 'pending'
    check (status in ('pending', 'active', 'disabled')),
  is_superadmin boolean not null default false,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists apel_users_role_id_idx on apel_users (role_id);

drop trigger if exists apel_users_touch on apel_users;
create trigger apel_users_touch
  before update on apel_users
  for each row execute function apel_touch_updated_at();

-- ---------------------------------------------------------------------------
-- One-time sign-in codes. A new request invalidates the previous codes for
-- that email (the app sets consumed_at on them), so at most one is live.
-- ---------------------------------------------------------------------------
create table if not exists apel_login_codes (
  id bigint generated by default as identity primary key,
  email text not null,
  code_hash text not null,
  expires_at timestamptz not null,
  attempts int not null default 0,
  consumed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists apel_login_codes_email_created_idx
  on apel_login_codes (email, created_at desc);

-- ---------------------------------------------------------------------------
-- Sessions
-- ---------------------------------------------------------------------------
create table if not exists apel_sessions (
  token_hash text primary key,
  user_id uuid not null references apel_users (id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists apel_sessions_user_id_idx on apel_sessions (user_id);

-- ---------------------------------------------------------------------------
-- Lock all three to the service role.
-- ---------------------------------------------------------------------------
alter table apel_users enable row level security;
alter table apel_login_codes enable row level security;
alter table apel_sessions enable row level security;

revoke all on table apel_users from anon, authenticated;
revoke all on table apel_login_codes from anon, authenticated;
revoke all on table apel_sessions from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Check a submitted code atomically. Locks the latest live code for the email
-- so two concurrent submissions cannot both spend the same attempt, then:
--   'ok'      — code matched; it is now consumed and cannot be reused
--   'invalid' — wrong code; attempts left
--   'locked'  — 5 wrong attempts; the user must request a new code
--   'expired' — no live code (never sent, expired, used or superseded)
-- ---------------------------------------------------------------------------
create or replace function apel_consume_login_code(p_email text, p_code_hash text)
returns text
language plpgsql
set search_path = public, pg_temp
as $$
declare
  c apel_login_codes%rowtype;
begin
  select * into c
  from apel_login_codes
  where email = p_email and consumed_at is null
  order by created_at desc
  limit 1
  for update;

  if not found or c.expires_at <= now() then
    return 'expired';
  end if;

  if c.attempts >= 5 then
    return 'locked';
  end if;

  if c.code_hash = p_code_hash then
    update apel_login_codes set consumed_at = now() where id = c.id;
    return 'ok';
  end if;

  update apel_login_codes set attempts = attempts + 1 where id = c.id;
  return case when c.attempts + 1 >= 5 then 'locked' else 'invalid' end;
end;
$$;

-- Functions in public are executable by everyone (and exposed over the REST
-- API) by default — keep this one server-side only.
revoke execute on function apel_consume_login_code(text, text) from public, anon, authenticated;
grant execute on function apel_consume_login_code(text, text) to service_role;

-- ---------------------------------------------------------------------------
-- Carry over the accounts created under 0003 (same id, role, status and
-- superadmin flag), then make sure the seed administrator from 0003 exists and
-- is an active superadmin.
-- ---------------------------------------------------------------------------
insert into apel_users (id, email, full_name, role_id, status, is_superadmin, created_at)
select p.id, lower(p.email), p.full_name, p.role_id, p.status, p.is_superadmin, p.created_at
from profiles p
where p.email is not null
on conflict do nothing;

