-- UNITAR APEL.Q Tracker — adds the two tables the app needs on top of the
-- existing public.apel and public.apel_advisors tables.
-- Run this in the Supabase SQL Editor.

-- Selection lists for internal/external assessors and moderators
create table if not exists apel_assessors (
  id bigint generated by default as identity primary key,
  name text not null,
  role text not null check (role in ('INTERNAL', 'EXTERNAL', 'MODERATOR')),
  created_at timestamptz not null default now()
);

-- Notes & follow-ups per learner
create table if not exists apel_notes (
  id bigint generated by default as identity primary key,
  learner_id bigint not null references apel (id) on delete cascade,
  body text not null,
  follow_up_date date,
  author text,
  created_at timestamptz not null default now()
);

create index if not exists apel_notes_learner_id_idx on apel_notes (learner_id);

-- v1 runs without login, so the anon key gets full access. Before exposing
-- this app outside the unit, add Supabase Auth and tighten these policies.
alter table apel_assessors enable row level security;
alter table apel_notes enable row level security;

drop policy if exists "tracker anon full access" on apel_assessors;
create policy "tracker anon full access" on apel_assessors for all using (true) with check (true);
drop policy if exists "tracker anon full access" on apel_notes;
create policy "tracker anon full access" on apel_notes for all using (true) with check (true);

-- The existing apel and apel_advisors tables currently allow anon reads but
-- block writes, so the app's add/edit/delete forms fail. These policies open
-- writes for the anon key as well.
drop policy if exists "tracker anon full access" on apel;
create policy "tracker anon full access" on apel for all using (true) with check (true);
drop policy if exists "tracker anon full access" on apel_advisors;
create policy "tracker anon full access" on apel_advisors for all using (true) with check (true);
